# Builds supabase/functions/guide/content.ts from Venture's web/index.html,
# tagging every fillable spot with a stable field id. Re-run if Venture edits.
import re, json, html
SRC='/workspace/marriage-ministry/companion-guide/web/index.html'
OUT='/workspace/nfoa-site/supabase/functions/guide/content.ts'
s=open(SRC,encoding='utf8').read()
css=re.search(r'<style>(.*?)</style>',s,re.S).group(1)
body=re.search(r'<main>(.*)</main>',s,re.S).group(1)
css=re.sub(r'@font-face\{[^}]*\}','',css)
# scope css under #g
def scope_sel(sel):
    out=[]
    for p in sel.split(','):
        p=p.strip()
        if p in('body',':root'): out.append('#g')
        elif p.startswith('*') : out.append('#g '+p+', #g')
        elif p.startswith('main'): out.append('#g'+p[4:])
        else: out.append('#g '+p)
    return ','.join(out)
def scope(c):
    res='';i=0
    while i<len(c):
        if c[i:i+6]=='@media':
            j=c.index('{',i);depth=1;k=j+1
            while depth:
                depth+= c[k]=='{'; depth-= c[k]=='}'; k+=1
            inner=c[j+1:k-1]
            if '@page' in inner:
                pg=re.search(r'@page\{[^}]*\}',inner).group(0); inner=inner.replace(pg,'')
                res+=c[i:j+1]+pg+scope(inner)+'}'
            else: res+=c[i:j+1]+scope(inner)+'}'
            i=k
        else:
            j=c.find('{',i)
            if j<0: break
            k=c.index('}',j)
            sel=c[i:j].strip()
            if sel: res+=scope_sel(sel)+c[j:k+1]
            i=k+1
    return res
css=scope(css)
# Venture tagged fields (data-field-id). We only add what Larry asked for that
# is not in his file: a "This Week" checkbox per chapter, Stop-Loss agreement
# checkboxes, and typed signatures in place of the div.sigpad placeholders.
FJ=json.load(open('/workspace/marriage-ministry/companion-guide/web/fields.json'))['fields']
types={f['id']:f['type'] for f in FJ}
secs=re.split(r'(?=<section )',body)
wk=None; out=[]
for sec in secs:
    m=re.search(r'data-field-id="(w\d\d-ch\d\d)-',sec)
    if m: wk=m.group(1)
    def tw(mm):
        i=f'{wk}-thisweek'; types[i]='checkbox'
        return mm.group(0)[:-6]+f'<label class="chk"><input type="checkbox" data-field-id="{i}" data-field-type="checkbox" id="{i}" name="{i}"> We did this</label></div>'
    if wk: sec=re.sub(r'<div class="card gold"><h4>This Week</h4><p>.*?</p></div>',tw,sec,flags=re.S)
    if 'Building Our Stop-Loss Agreement' in sec:
        add=''
        for n in (1,2):
            i=f'{wk}-stoploss-agree-{n}'; types[i]='checkbox'
            add+=f'<label class="chk"><input type="checkbox" data-field-id="{i}" data-field-type="checkbox" id="{i}" name="{i}"> Spouse {n}: I agree to our Stop-Loss Agreement</label>'
        sec=sec.replace('</div><div class="pw">','<div class="agree">'+add+'</div></div><div class="pw">',1)
    out.append(sec)
body=''.join(out)
body=re.sub(r'<div class="sigpad"([^>]*?)role="img"></div>',lambda mm:'<input type="text" class="fld sigtype" maxlength="120" placeholder="Type your full name" autocomplete="name"'+mm.group(1).replace('data-field-type="signature"','data-field-type="signature"')+'>',body)
assert 'sigpad' not in body
ids=list(types)
found=re.findall(r'data-field-id="([^"]+)"',body)
assert sorted(found)==sorted(ids) and len(found)==len(set(found)), (len(found),len(ids))
body=body.replace('src="assets/larry-ro.jpg"','src="/assets/guide-cover.jpg"')
assert len(ids)==len(set(ids)),'dup ids'
for bad in ('\u2013','\u2014','&mdash;','&ndash;'):
    assert bad not in body+css, bad
open(OUT,'w',encoding='utf8').write('// GENERATED by marriage-ministry/event-bundle/build/build_guide.py from Venture\'s\n// companion-guide/web/index.html (12-week v1). Do not hand edit.\nexport const GUIDE = '+json.dumps({'title':'The Full 12-Week Companion Guide','version':'12wk-v1','css':css,'html':body,'fields':types},ensure_ascii=False)+';\n')
print(len(ids),'fields', sum(1 for i in ids if 'thisweek' in i),'thisweek', len(body))
